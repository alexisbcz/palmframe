const camel = (name: string) =>
  name.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase())

async function doodle(file: string) {
  const url = `https://raw.githubusercontent.com/oreo-design/doodle-icons/${OREO_COMMIT}/icons/${file}.svg`
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${file}: ${response.status}`)
  const svg = await response.text()
  return [
    ...svg.matchAll(
      /<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*?)\/?>/g
    ),
  ].map(([, tag, attrs]) => [
    tag,
    Object.fromEntries(
      [...attrs!.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [
        camel(key!),
        value,
      ])
    ),
  ])
}

