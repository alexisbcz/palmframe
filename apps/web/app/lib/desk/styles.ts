// House styles, written as ordinary Vale rules. Each one takes a writer's or a
// reader's published advice and turns the checkable part of it into patterns.
// They're tributes to the advice, not to the prose: nobody passes a Hemingway
// lint and gets Hemingway.

export interface HouseStyle {
  id: string
  // Printed on the card. Proper names, so not translated.
  name: string
  source: string
  language: "en" | "fr"
  for: Kind[]
  rules: Record<string, ValeRule>
}

