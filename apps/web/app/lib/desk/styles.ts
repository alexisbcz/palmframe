const compiledStyles = new Map<string, CompiledRule[]>()

export function compileStyle(style: HouseStyle) {
  let rules = compiledStyles.get(style.id)
  if (!rules) {
    rules = Object.entries(style.rules).map(([name, rule]) =>
      compileRule(`${style.name}.${name}`, rule)
    )
    compiledStyles.set(style.id, rules)
  }
  return rules
}
